-- AI spot recommendations (the ✨ button on every page).
--
-- The recommend-spots Edge Function (supabase/functions/recommend-spots) writes
-- one row here every time it asks Gemini for recommendations. The table does
-- two jobs:
--   * cache:      a finished row with the same cache_key is reused, so the same
--                 favorites + the same spots never call Gemini twice;
--   * rate limit: rows from the last hour / day are counted per student and for
--                 the whole site, to stay inside Gemini's free-tier quota.
--
-- Only the Edge Function (service role) reads or writes it. Students can't see
-- it from the browser: RLS is on and there are no policies.
--
-- Paste the whole file into Supabase -> SQL Editor -> New query -> Run.
-- Safe to run more than once.

create table if not exists public.ai_recommendation (
  ai_recommendation_id bigint generated by default as identity primary key,
  user_id              bigint not null references public.student_user (user_id) on delete cascade,
  cache_key            text not null,
  status               text not null default 'pending' check (status in ('pending', 'ok', 'error')),
  recommendations      jsonb,          -- [{ "spot_id": 12, "reason": "..." }]
  model_name           text,
  error_message        text,
  created_at           timestamptz not null default now()
);

create index if not exists ai_recommendation_user_cache_idx
  on public.ai_recommendation (user_id, cache_key, created_at desc);
create index if not exists ai_recommendation_user_created_idx
  on public.ai_recommendation (user_id, created_at desc);
create index if not exists ai_recommendation_created_idx
  on public.ai_recommendation (created_at desc);

alter table public.ai_recommendation enable row level security;
revoke all on public.ai_recommendation from anon, authenticated;
grant all on public.ai_recommendation to service_role;

-- Old rows are only useful for a week (cache) or a day (rate limit). The Edge
-- Function deletes this student's rows older than 30 days as it goes, so the
-- table stays small without a cron job.

select 'ai_recommendation table ready' as status;
