-- BYU Study Spot Finder: tables from the starting ERD (docs/erd/erd.png).
-- 8 tables: 6 entities plus 2 join tables for the many-to-many relationships.

-- ---------------------------------------------------------------------------
-- Building
-- ---------------------------------------------------------------------------
create table public.building (
  building_id          bigint generated by default as identity primary key,
  building_code        text not null unique,          -- e.g. HBLL
  building_name        text not null,
  campus_map_latitude  numeric(9, 6),
  campus_map_longitude numeric(9, 6),
  floor_count          int check (floor_count > 0),
  weekday_open_time    time,
  weekday_close_time   time
);

-- ---------------------------------------------------------------------------
-- Student User
-- ---------------------------------------------------------------------------
create table public.student_user (
  user_id            bigint generated by default as identity primary key,
  byu_net_id         text not null unique,
  display_name       text not null,
  byu_email          text not null unique,
  account_created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Study Spot
-- Building contains Study Spot (one-to-many).
-- Student User submits Study Spot (one-to-many); null = built-in sample spot.
-- ---------------------------------------------------------------------------
create table public.study_spot (
  study_spot_id          bigint generated by default as identity primary key,
  building_id            bigint not null references public.building (building_id) on delete cascade,
  submitted_by_user_id   bigint references public.student_user (user_id) on delete set null,
  spot_name              text not null,
  floor_number           int,
  location_description   text,
  is_indoors             boolean not null default true,
  seat_count             int check (seat_count >= 0),
  max_group_size         int check (max_group_size > 0),
  noise_level            text check (noise_level in ('Silent', 'Quiet', 'Moderate', 'Loud')),
  typical_busyness_level text check (typical_busyness_level in ('Low', 'Moderate', 'High')),
  floor_plan_x_percent   numeric(5, 2) check (floor_plan_x_percent between 0 and 100),
  floor_plan_y_percent   numeric(5, 2) check (floor_plan_y_percent between 0 and 100),
  is_sample_spot         boolean not null default false,
  created_at             timestamptz not null default now()
);

create index study_spot_building_id_idx on public.study_spot (building_id);
create index study_spot_submitted_by_user_id_idx on public.study_spot (submitted_by_user_id);

-- ---------------------------------------------------------------------------
-- Amenity
-- ---------------------------------------------------------------------------
create table public.amenity (
  amenity_id        bigint generated by default as identity primary key,
  amenity_name      text not null unique,             -- e.g. Power outlets
  amenity_icon_name text
);

-- ---------------------------------------------------------------------------
-- Study Spot Amenity (join table: Study Spot <-> Amenity)
-- ---------------------------------------------------------------------------
create table public.study_spot_amenity (
  study_spot_id bigint not null references public.study_spot (study_spot_id) on delete cascade,
  amenity_id    bigint not null references public.amenity (amenity_id) on delete cascade,
  primary key (study_spot_id, amenity_id)
);

create index study_spot_amenity_amenity_id_idx on public.study_spot_amenity (amenity_id);

-- ---------------------------------------------------------------------------
-- Spot Rating
-- Student User writes Spot Rating; Study Spot receives Spot Rating.
-- ---------------------------------------------------------------------------
create table public.spot_rating (
  spot_rating_id bigint generated by default as identity primary key,
  user_id        bigint not null references public.student_user (user_id) on delete cascade,
  study_spot_id  bigint not null references public.study_spot (study_spot_id) on delete cascade,
  star_rating    int not null check (star_rating between 1 and 5),
  review_comment text,
  rated_at       timestamptz not null default now()
);

create index spot_rating_user_id_idx on public.spot_rating (user_id);
create index spot_rating_study_spot_id_idx on public.spot_rating (study_spot_id);

-- ---------------------------------------------------------------------------
-- Favorite Spot (join table: Student User <-> Study Spot)
-- ---------------------------------------------------------------------------
create table public.favorite_spot (
  user_id       bigint not null references public.student_user (user_id) on delete cascade,
  study_spot_id bigint not null references public.study_spot (study_spot_id) on delete cascade,
  favorited_at  timestamptz not null default now(),
  primary key (user_id, study_spot_id)
);

create index favorite_spot_study_spot_id_idx on public.favorite_spot (study_spot_id);

-- ---------------------------------------------------------------------------
-- Saved Filter
-- Student User saves Saved Filter (one-to-many).
-- ---------------------------------------------------------------------------
create table public.saved_filter (
  saved_filter_id           bigint generated by default as identity primary key,
  user_id                   bigint not null references public.student_user (user_id) on delete cascade,
  filter_name               text not null,
  group_size                int check (group_size > 0),
  preferred_noise_level     text check (preferred_noise_level in ('Silent', 'Quiet', 'Moderate', 'Loud')),
  indoor_outdoor_preference text not null default 'Either'
                            check (indoor_outdoor_preference in ('Indoor', 'Outdoor', 'Either')),
  max_busyness_level        text check (max_busyness_level in ('Low', 'Moderate', 'High')),
  created_at                timestamptz not null default now()
);

create index saved_filter_user_id_idx on public.saved_filter (user_id);

-- ---------------------------------------------------------------------------
-- Row Level Security
-- Supabase exposes the public schema through its API, so every table has RLS on.
-- Campus data (buildings, spots, amenities, ratings) is readable by anyone.
-- Student data (users, favorites, saved filters) has no policies yet, so it is
-- only reachable from the dashboard / service role until sign-in is added.
-- ---------------------------------------------------------------------------
alter table public.building           enable row level security;
alter table public.student_user       enable row level security;
alter table public.study_spot         enable row level security;
alter table public.amenity            enable row level security;
alter table public.study_spot_amenity enable row level security;
alter table public.spot_rating        enable row level security;
alter table public.favorite_spot      enable row level security;
alter table public.saved_filter       enable row level security;

create policy "Anyone can read buildings"
  on public.building for select to anon, authenticated using (true);
create policy "Anyone can read study spots"
  on public.study_spot for select to anon, authenticated using (true);
create policy "Anyone can read amenities"
  on public.amenity for select to anon, authenticated using (true);
create policy "Anyone can read study spot amenities"
  on public.study_spot_amenity for select to anon, authenticated using (true);
create policy "Anyone can read spot ratings"
  on public.spot_rating for select to anon, authenticated using (true);
